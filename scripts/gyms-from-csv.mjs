/**
 * Turns the gym research CSV into lib/gyms/data.ts for the /gyms page.
 *
 *   node scripts/gyms-from-csv.mjs data/taiwan_bouldering_2026-10-07.csv
 *
 * Closed and not-yet-open gyms are left out. Free-text fields that only say
 * "待確認" (to be confirmed) are dropped, so the page shows nothing rather
 * than a placeholder. The CSV's own caveats (hours_status, notes, …) are kept.
 */
import { readFile, writeFile } from "node:fs/promises";

const [, , input] = process.argv;

if (!input) throw new Error("Usage: node scripts/gyms-from-csv.mjs <csv>");

/** RFC 4180-ish: quoted fields, doubled quotes, newlines inside quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];

    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field || row.length) rows.push([...row, field]);

  const [head, ...body] = rows.filter((r) => r.some((v) => v.trim()));

  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

const UNKNOWN = /^(待確認|待詢問場館|待公布|)$/;
const text = (v) => (UNKNOWN.test(v.trim()) ? undefined : v.trim());
const num = (v) => (v.trim() ? Number(v) : undefined);

function kind(r) {
  switch (r.bouldering_count_group) {
    case "一般抱石候選":
      return r.category === "抱石" ? "boulder" : "mixed";
    case "上攀／抱石待確認":
      return "rope";
    case "兒童／小型抱石":
      return "kids";
    case "戶外／半戶外":
      return "outdoor";
    case "營運狀態待確認":
      return r.category === "抱石" ? "boulder" : r.category.startsWith("上攀") ? "rope" : "mixed";
    default:
      return null; // closed or planned
  }
}

const rows = parseCsv((await readFile(input, "utf8")).replace(/^﻿/, ""));
const gyms = rows
  .map((r) => ({ r, kind: kind(r) }))
  .filter(({ kind }) => kind)
  .map(({ r, kind }) => {
    // A usable price is a day pass, a shoe rental, or a published note such
    // as hourly or time-slot tickets. "未取得…", "不適用…" and "尚未公布" mean none.
    const hasNotes = !/^(未取得|不適用|尚未公布)/.test(r.price_status);
    const priced =
      r.weekday_daypass_twd || r.weekend_daypass_twd || r.shoe_rental_twd || hasNotes;

    return {
      id: r.id,
      name: r.name.trim(),
      city: r.city,
      district: r.district,
      address: text(r.address),
      kind,
      confirmed: r.status === "公開資料可查",
      category: r.category,
      hours: text(r.opening_hours)
        ?.split(/；|;/)
        .map((s) => s.trim())
        .filter(Boolean),
      hoursNote: text(r.hours_status),
      price: priced
        ? {
            weekday: num(r.weekday_daypass_twd),
            weekend: num(r.weekend_daypass_twd),
            shoes: num(r.shoe_rental_twd),
            // Hourly, time-slot or intro prices, e.g. "下午350；晚上450；星光320".
            notes: hasNotes ? text(r.price_notes)?.replace(/[。.]+$/, "") : undefined,
            source: r.price_status,
          }
        : undefined,
      courses: text(r.trial_and_courses),
      facilities: text(r.facilities),
      booking: text(r.booking),
      phone: text(r.phone),
      website: text(r.website),
      instagram: text(r.instagram),
      facebook: text(r.facebook),
      notes: text(r.notes),
      lat: num(r.latitude),
      lng: num(r.longitude),
      mapsUrl: text(r.maps_search_url),
    };
  })
  // drop undefined keys so the generated file stays readable
  .map((g) => JSON.parse(JSON.stringify(g)));

const checkedAt = rows.map((r) => r.checked_at).sort().at(-1);
const out = `// Generated by scripts/gyms-from-csv.mjs from ${input.split("/").at(-1)}. Do not edit by hand.
import type { Gym } from "./types";

export const checkedAt = ${JSON.stringify(checkedAt)};

export const gyms: Gym[] = ${JSON.stringify(gyms, null, 2)};
`;

await writeFile("lib/gyms/data.ts", out);
console.log(`${gyms.length} gyms (of ${rows.length} rows), checked ${checkedAt}`);

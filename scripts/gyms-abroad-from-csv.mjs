/**
 * Turns the app's Hong Kong, Singapore and Malaysia gym lists into
 * lib/gyms/data-abroad.ts. The CSVs are copied from the VARO app repo
 * (varo/data/gyms.*.csv, the same files imported into its database):
 *
 *   node scripts/gyms-abroad-from-csv.mjs data/gyms.hongkong.csv data/gyms.singapore.csv data/gyms.malaysia.csv
 *
 * These lists have no hours or prices. Notes about grading scales are left
 * out (they matter to the app, not to someone choosing a gym); "僅抱石" is
 * already the gym's kind. Gyms whose status or address the research couldn't
 * confirm are marked unconfirmed, like the Taiwan list.
 */
import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";

const inputs = process.argv.slice(2);

if (!inputs.length)
  throw new Error("Usage: node scripts/gyms-abroad-from-csv.mjs <csv>...");

/** RFC 4180-ish: quoted fields, doubled quotes, newlines inside quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];

    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field || row.length) rows.push([...row, field]);

  const [head, ...body] = rows.filter((r) => r.some((v) => v.trim()));

  return body.map((r) =>
    Object.fromEntries(head.map((h, i) => [h.replace(/^﻿/, ""), r[i] ?? ""])),
  );
}

const GRADING = /等級|分級|級數|\d+\s*級|V\/Font|V3\/4|推定 V/;
const UNCONFIRMED =
  /營運狀態待確認|地址來源矛盾|開業日期未經官方公告確認|是否為室內待確認/;
const ROPES = /頂繩|先鋒|高牆/;
const ROPES_NOT_OPEN = /頂繩只開放給兒童|舊資料有頂繩/;

const segments = (note) =>
  note
    .split(/[；;]/)
    .map((s) => s.trim())
    .filter(Boolean);

function kind(note) {
  if (segments(note).includes("半戶外")) return "outdoor";
  if (ROPES.test(note) && !ROPES_NOT_OPEN.test(note)) return "mixed";

  return "boulder";
}

const CATEGORY = { boulder: "抱石", mixed: "抱石＋上攀", outdoor: "半戶外抱石" };

const gyms = [];
const checked = new Set();

for (const input of inputs) {
  for (const r of parseCsv(await readFile(input, "utf8"))) {
    const [prefix, id] = r.external_id.split(":");
    const country = prefix.toUpperCase();
    const note = r.status_note.trim();
    const k = kind(note);
    const notes = segments(note)
      .filter((s) => !GRADING.test(s) && s !== "僅抱石")
      .join("；");
    const name = r.branch ? `${r.name}・${r.branch}` : r.name;

    checked.add(r.last_verified_at);
    gyms.push({
      id,
      country,
      name,
      city: r.city,
      district: r.district,
      ...(r.address ? { address: r.address } : {}),
      kind: k,
      confirmed: !UNCONFIRMED.test(note),
      category: CATEGORY[k],
      ...(r.website ? { website: r.website } : {}),
      ...(r.instagram ? { instagram: r.instagram } : {}),
      ...(r.facebook ? { facebook: r.facebook } : {}),
      ...(notes ? { notes } : {}),
      ...(r.latitude ? { lat: Number(r.latitude) } : {}),
      ...(r.longitude ? { lng: Number(r.longitude) } : {}),
      mapsUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
        `${r.name} ${r.address || r.city}`,
      )}`,
    });
  }
}

const ids = new Set();

for (const g of gyms) {
  if (ids.has(g.id)) throw new Error(`Duplicate id: ${g.id}`);
  ids.add(g.id);
}

const out = `// Generated by scripts/gyms-abroad-from-csv.mjs from ${inputs
  .map((p) => basename(p))
  .join(", ")}. Do not edit by hand.
import type { Gym } from "./types";

export const abroadCheckedAt = "${[...checked].sort().at(-1)}";

export const abroadGyms: Gym[] = ${JSON.stringify(gyms, null, 2)};
`;

await writeFile("lib/gyms/data-abroad.ts", out);
console.log(`lib/gyms/data-abroad.ts: ${gyms.length} gyms`);
